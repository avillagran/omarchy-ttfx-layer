// utils/hexterm.s - xterm-256 <-> RGB (src/utils/hexterm.rs).
//
// hex_to_xterm is the minimum mean absolute channel difference over codes
// 0..=255 in order, first minimum winning. The scan compares integer sums,
// which orders exactly like upstream's sum / 3. A scalar scan (the x86
// TIER 1 path); results are memoized per RGB value.
// (XTERM_MEMO_BYTES comes from defs.inc: u16 per RGB value, code + 1,
// 0 = unknown.)

    .text

// hex_to_xterm(w0=0xRRGGBB) -> w9 = xterm code. Clobbers x1, x2, x3, x4,
// x10, x12-x14, x16, x17 (the first call's reserve keeps x0, x5, x11).
hex_to_xterm:
    LDX     x9, xterm_memo
    cbnz    x9, hex_to_xterm.memo
    PUSH2   x0, x30
    PUSH2   x5, x11
    mov     x0, #XTERM_MEMO_BYTES
    bl      reserve
    STX     x9, xterm_memo
    POP2    x5, x11
    POP2    x0, x30
hex_to_xterm.memo:
    and     w2, w0, #0xffffff
    ldrh    w3, [x9, x2, lsl #1]
    cbz     w3, hex_to_xterm.scan
    sub     w9, w3, #1
    ret
hex_to_xterm.scan:
    // scalar scan, strict < so the first minimum wins; x2 keeps the
    // memo index
    mov     w4, #0x7fffffff             // best difference
    mov     w9, #0                      // best code
    ADRG    x1, xterm_rgb
    mov     w3, #0
hex_to_xterm.code:
    ldr     w13, [x1, x3, lsl #2]
    mov     w12, #0
    .irp    sh, 0, 8, 16
    ubfx    w14, w13, #\sh, #8
    ubfx    w10, w0, #\sh, #8
    subs    w14, w14, w10
    cneg    w14, w14, mi                // |difference|
    add     w12, w12, w14
    .endr
    cmp     w12, w4
    csel    w9, w3, w9, lo
    csel    w4, w12, w4, lo
    add     w3, w3, #1
    cmp     w3, #256
    b.lo    hex_to_xterm.code
    LDX     x3, xterm_memo
    add     w1, w9, #1
    strh    w1, [x3, x2, lsl #1]
    ret

// dropped: xterm_byte_mask xterm_diffs (the AVX-512 scan's data)

